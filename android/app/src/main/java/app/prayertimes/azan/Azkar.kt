/** حسابات أوقات الأذكار (منطق خالص قابل للاختبار) */
object AzkarTimes {
    /** تذكير الأذكار بعد الأذان بعدد من الدقائق */
    const val REMINDER_DELAY_MIN = 15L

    /** الأذكار المناسبة الآن: من الفجر حتى العصر أذكار الصباح، وغير ذلك أذكار المساء */
    fun suggested(times: Map<Prayer, Instant>, now: Instant): AzkarKind =
        if (!now.isBefore(times.getValue(Prayer.FAJR)) && now.isBefore(times.getValue(Prayer.ASR))) AzkarKind.MORNING
        else AzkarKind.EVENING

    /** موعد تذكير الأذكار القادم: بعد الفجر (صباح) أو بعد العصر (مساء) */
    fun nextReminder(loc: PrayerSchedule.Location, after: Instant): Pair<AzkarKind, Instant> {
        val start = PrayerSchedule.today(loc, after).minusDays(1)
        for (i in 0..2) {
            val t = PrayerSchedule.day(loc, start.plusDays(i.toLong()))
            val morning = t.getValue(Prayer.FAJR).plus(Duration.ofMinutes(REMINDER_DELAY_MIN))
            val evening = t.getValue(Prayer.ASR).plus(Duration.ofMinutes(REMINDER_DELAY_MIN))
            if (morning.isAfter(after)) return AzkarKind.MORNING to morning
            if (evening.isAfter(after)) return AzkarKind.EVENING to evening
        }
        error("unreachable")
    }

    /**
     * موعد إشعار الذكر القادم: بعد intervalHours، داخل نافذة اليوم [startHour, endHour)
     * بالتوقيت المحلي للموقع؛ وإلا فأول النافذة التالية.
     */
    fun nextDhikr(after: Instant, zone: ZoneId, intervalHours: Int, startHour: Int = 8, endHour: Int = 22): Instant {
        val candidate = after.plus(Duration.ofHours(intervalHours.coerceIn(1, 12).toLong())).atZone(zone)
        val dayStart = candidate.toLocalDate().atTime(startHour, 0).atZone(zone)
        val dayEnd = candidate.toLocalDate().atTime(endHour, 0).atZone(zone)
        return when {
            candidate.isBefore(dayStart) -> dayStart.toInstant()
            !candidate.isBefore(dayEnd) -> dayStart.plusDays(1).toInstant()
            else -> candidate.toInstant()
        }
    }
}
